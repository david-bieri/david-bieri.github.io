#!/usr/bin/env python3
"""Emit the CV's 'Media coverage & contributions' section as LaTeX from data/media.csv.

Usage:  python3 tools/build_cv_media.py > cv/media_section.tex
Then \\input{media_section} in the CV where the hand-written section used to be.
Rows with notes containing 'title-from-program' are listed by outlet and programme only.
"""
import csv, os, re, sys, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = list(csv.DictReader(open(os.path.join(ROOT, "data", "media.csv"), encoding="utf-8")))
rows.sort(key=lambda r: r["date"], reverse=True)
MON = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
def tex(s):
    s = re.sub(r"\s*\([^)]*[^\x00-\u024F][^)]*\)", "", s)   # drop parentheticals in non-Latin scripts, e.g. (凤凰卫视)
    s = "".join(c for c in s if ord(c) < 0x0250 or c in "\u2018\u2019\u201c\u201d\u2013\u2014")  # pdflatex-safe
    s = s.replace("\\", "\\textbackslash{}")
    for a, b in [("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")]:
        s = s.replace(a, b)
    s = re.sub(r'"([^"]*)"', r"\\enquote{\1}", s)
    s = s.replace("‘", "`").replace("’", "'").replace("“", "``").replace("”", "''").replace("—", "---").replace("–", "--")
    return s
def url(u):
    return u.replace("%", "\\%").replace("#", "\\#")
def month(d):
    return MON[int(d[5:7]) - 1] + " " + d[:4]
by_year = collections.OrderedDict()
for r in rows:
    by_year.setdefault(r["date"][:4], []).append(r)
outlets = collections.Counter(r["outlet"] for r in rows)
tiers = collections.Counter(r["tier"] for r in rows)
years = sorted(by_year)
out = []
out.append("%% GENERATED by tools/build_cv_media.py from data/media.csv -- do not edit by hand.")
out.append("\\subsection*{Media coverage \\& contributions}")
out.append(f"\\noindent {len(rows)} interviews and expert contributions, {years[0]}--{years[-1]}, across {len(outlets)} outlets "
           f"({tiers['national']} national, {tiers['international']} international). Television, radio, print and online; live and recorded. "
           "Frequent outlets: Marketplace, CNN, CBS, ABC, FOX 5 Washington, NPR/RadioIQ, WSLS, WFXR. "
           "The complete, searchable archive is at \\href{https://david-bieri.com/media.html}{david-bieri.com/media}.\\\\[4pt]")
out.append("% Set \\newcommand{\\CVmediaRecent}{2} in the CV preamble to show only the most recent N years here;")
out.append("% the remaining years are wrapped in \\CVmediaArchive{...} and print only if that macro is defined as identity.")
out.append("\\providecommand{\\CVmediaRecent}{99}\\providecommand{\\CVmediaArchive}[1]{}")
for i, y in enumerate(sorted(by_year, reverse=True)):
    if i == int(os.environ.get("CV_RECENT", "2")):
        out.append(f"\\ifnum\\CVmediaRecent<{i+1}\\relax\\noindent\\emph{{Earlier coverage ({years[0]}--{int(y)}), {sum(len(by_year[k]) for k in by_year if k <= y)} items, is listed in the online archive.}}\\fi")
        out.append(f"\\ifnum\\CVmediaRecent>{i}\\relax")
        tail_open = True
    out.append(f"\\subsubsection*{{{y}}}")
    out.append("\\begin{itemize}[--]\n\\itemsep0em")
    for r in by_year[y]:
        o = tex(r["outlet"]); p = tex(r["program"]) if r["program"] and r["program"].lower() != r["outlet"].lower() else ""
        where = f"\\emph{{{o}}}" + (f", {p}" if p else "")
        kind = {"tv": "TV", "radio": "radio", "podcast": "podcast"}.get(r["type"], "")
        if "title-from-program" in r.get("notes", ""):
            head = f"Interview ({kind})" if kind else "Interview"
        else:
            t = r["title"]
            m = re.match(r"^(.{20,110}?)(?:[.:;]\s|\s[-\u2014]\s)(.+)$", t)
            if m and len(t) > 110: t = m.group(1)
            t = tex(t.rstrip(" .:"))
            head = f"\\href{{{url(r['url'])}}}{{{t}}}" if r["url"] else t
        out.append(f"    \\item {head}, {where}, {month(r['date'])}.")
    out.append("\\end{itemize}")
if len(by_year) > int(os.environ.get("CV_RECENT", "2")):
    out.append("\\fi")
print("\n".join(out))
